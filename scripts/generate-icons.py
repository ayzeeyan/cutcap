"""Converts the authored 16 px icon SVGs into Avalonia path data.

Usage: python -I scripts/generate-icons.py
Reads apps/CutCap.Desktop/Assets/Icons/*.svg and rewrites
apps/CutCap.Desktop/Controls/IconData.g.cs. Supports the small subset the icons
use: <path d>, <rect x y width height rx>, <circle cx cy r>. Elements with a
fill are emitted as fill geometry; everything else is stroked (1.5 px, round).
"""
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "apps" / "CutCap.Desktop" / "Assets" / "Icons"
TARGET = ROOT / "apps" / "CutCap.Desktop" / "Controls" / "IconData.g.cs"
NS = "{http://www.w3.org/2000/svg}"


def num(value: float) -> str:
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


def rect(e: ET.Element) -> str:
    x, y = float(e.get("x", 0)), float(e.get("y", 0))
    w, h = float(e.get("width")), float(e.get("height"))
    r = float(e.get("rx", 0))
    if r == 0:
        return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
    return (
        f"M{num(x + r)},{num(y)}H{num(x + w - r)}A{num(r)},{num(r)} 0 0 1 {num(x + w)},{num(y + r)}"
        f"V{num(y + h - r)}A{num(r)},{num(r)} 0 0 1 {num(x + w - r)},{num(y + h)}"
        f"H{num(x + r)}A{num(r)},{num(r)} 0 0 1 {num(x)},{num(y + h - r)}"
        f"V{num(y + r)}A{num(r)},{num(r)} 0 0 1 {num(x + r)},{num(y)}Z"
    )


def circle(e: ET.Element) -> str:
    cx, cy, r = float(e.get("cx")), float(e.get("cy")), float(e.get("r"))
    return (
        f"M{num(cx - r)},{num(cy)}A{num(r)},{num(r)} 0 1 1 {num(cx + r)},{num(cy)}"
        f"A{num(r)},{num(r)} 0 1 1 {num(cx - r)},{num(cy)}Z"
    )


def absolute_start(data: str) -> str:
    """Each SVG element starts at (0,0), but joined subpaths would not. A leading
    relative move is made absolute, keeping its implicit line-tos relative."""
    match = re.match(r"\s*m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)(.*)", data, re.S)
    if not match:
        return data
    rest = match.group(3).strip()
    if rest and (rest[0].isdigit() or rest[0] in "-."):
        rest = "l" + rest
    return f"M{match.group(1)} {match.group(2)}{rest}"


def convert(path: pathlib.Path) -> tuple[str, str]:
    stroke, fill = [], []
    for element in ET.parse(path).getroot().iter():
        tag = element.tag.replace(NS, "")
        if tag == "path":
            data = absolute_start(element.get("d"))
        elif tag == "rect":
            data = rect(element)
        elif tag == "circle":
            data = circle(element)
        else:
            continue
        filled = element.get("fill") not in (None, "none")
        (fill if filled else stroke).append(data)
    return " ".join(stroke), " ".join(fill)


def pascal(stem: str) -> str:
    return "".join(part.capitalize() for part in stem.split("-"))


def main() -> None:
    rows = []
    for svg in sorted(SOURCE.glob("*.svg")):
        stroke, fill = convert(svg)
        rows.append(f'        ["{pascal(svg.stem)}"] = ("{stroke}", "{fill}"),')
    TARGET.write_text(
        "// <auto-generated> by scripts/generate-icons.py from Assets/Icons/*.svg. Do not edit.\n"
        "namespace CutCap.Desktop.Controls;\n\n"
        "internal static class IconData\n{\n"
        "    /// <summary>Icon name → (stroke path data, fill path data) in a 16×16 box.</summary>\n"
        "    public static readonly IReadOnlyDictionary<string, (string Stroke, string Fill)> Paths =\n"
        "        new Dictionary<string, (string Stroke, string Fill)>(StringComparer.Ordinal)\n    {\n"
        + "\n".join(rows)
        + "\n    };\n}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(rows)} icons -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
